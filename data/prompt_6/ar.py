# إنشاء مجموعة من السلاسل تسمى المركبات
المركبات = {"سيارة أودي", "سيارة تويوتا", "سيارة مرسيدس", "سيارة بورش"}

# طلب من المستخدم إدخال فهرس السيارة
index = int(input("أدخل فهرس السيارة (0-3): "))

# التحقق من أن الفهرس صحيح
if 0 <= index < len(المركبات):
    # تحويل المجموعة إلى قائمة لاستخدام الفهرس
    المركبات_القائمة = list(المركبات)
    السيارة_المطلوبة = المركبات_القائمة[index]
    print(f"السيارة المطلوبة: {السيارة_المطلوبة}")
else:
    print("الفرز غير صحيح!")

# طباعة كل مركبة في المجموعة
print("\nكل المركبات:")
for مركبة in المركبات:
    print(مركبة)

# طلب إدخال اسم سيارة جديدة
سيارة_جديدة = input("\nأدخل اسم سيارة جديدة: ")
المركبات.add(سيارة_جديدة)

# طلب إدخال اسم سيارة للحذف
سيارة_للحذف = input("أدخل اسم سيارة للحذف: ")
if سيارة_للحذف in المركبات:
    المركبات.remove(سيارة_للحذف)
    print(f"تم حذف السيارة: {سيارة_للحذف}")
else:
    print(f"السيارة {سيارة_للحذف} غير موجودة في المجموعة!")

# طباعة المجموعة النهائية
print("\nالمجموعة النهائية:")
for مركبة in المركبات:
    print(مركبة)