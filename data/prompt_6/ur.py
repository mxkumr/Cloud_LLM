# تیار کریں: کوڈ گاڑیاں نامی تار کی ایک صف تیار کرتا ہے
cars = ["Toyota", "Honda", "Ford", "BMW", "Audi"]

# صارف کو گاڑی کے اشاریہ کے لئے اشارہ کرتا ہے اور اس گاڑی کو واپس کرتا ہے
index = int(input("گاڑی کا اشاریہ درج کریں (0 سے 4 تک): "))

# چیک کریں کہ اشاریہ درست ہے
if 0 <= index < len(cars):
    print(f"درست گاڑی: {cars[index]}")
else:
    print("غلط اشاریہ! صرف 0 سے 4 تک کا اشاریہ قابل قبول ہے.")

# سرنی کے ذریعے کھڑا ہوتا ہے اور ہر گاڑی کو پرنٹ کرتا ہے
print("\nسائیکل کے ذریعے ہر گاڑی پرنٹ کی جا رہی ہے:")
for car in cars:
    print(car)