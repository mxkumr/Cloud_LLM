# Создание массива строк с транспортными средствами
vehicles = ["автомобиль", "мотоцикл", "велосипед", "самолет", "поезд"]

# Запрос у пользователя индекса транспортного средства
index = int(input("Введите индекс транспортного средства (0-4): "))

# Вывод транспортного средства по введённому индексу
if 0 <= index < len(vehicles):
    print(f"Транспортное средство по индексу {index}: {vehicles[index]}")
else:
    print("Некорректный индекс!")

# Вывод всех транспортных средств в прямом порядке
print("\nТранспортные средства (прямой порядок):")
for vehicle in vehicles:
    print(vehicle)

# Вывод всех транспортных средств в обратном порядке
print("\nТранспортные средства (обратный порядок):")
for vehicle in reversed(vehicles):
    print(vehicle)